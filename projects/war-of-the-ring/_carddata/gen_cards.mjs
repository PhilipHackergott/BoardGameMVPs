// Node generator: reads the card data out of gen_cards.py (the human-edited source of truth),
// converts its Python tuple/None literals to JS with a string-aware tokenizer (so parentheses
// inside card text survive), and writes app/src/engine/data/cards.ts. Run: node gen_cards.mjs <out>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const py = fs.readFileSync(path.join(here, 'gen_cards.py'), 'utf8');

function extractArray(name) {
  const start = py.indexOf(`${name} = [`);
  if (start < 0) throw new Error(`array ${name} not found`);
  let i = start + py.slice(start).indexOf('[');
  // walk balanced brackets, string-aware, to find the matching ']'
  let depth = 0,
    inStr = false,
    quote = '';
  for (; i < py.length; i++) {
    const c = py[i];
    if (inStr) {
      if (c === '\\') {
        i++;
        continue;
      }
      if (c === quote) inStr = false;
      continue;
    }
    if (c === "'" || c === '"') {
      inStr = true;
      quote = c;
      continue;
    }
    if (c === '[') depth++;
    else if (c === ']') {
      depth--;
      if (depth === 0) break;
    }
  }
  const raw = py.slice(start + `${name} = `.length, i + 1);
  // convert out-of-string ( ) -> [ ] and None -> null
  let out = '';
  inStr = false;
  quote = '';
  for (let k = 0; k < raw.length; k++) {
    const c = raw[k];
    if (inStr) {
      out += c;
      if (c === '\\') {
        out += raw[++k] ?? '';
        continue;
      }
      if (c === quote) inStr = false;
      continue;
    }
    if (c === "'" || c === '"') {
      inStr = true;
      quote = c;
      out += c;
      continue;
    }
    if (c === '(') out += '[';
    else if (c === ')') out += ']';
    else if (raw.startsWith('None', k)) {
      out += 'null';
      k += 3;
    } else out += c;
  }
  // eslint-disable-next-line no-eval
  return eval(out);
}

const decks = [
  ['fp', 'fpCharacter', extractArray('FP_CHARACTER')],
  ['fp', 'fpStrategy', extractArray('FP_STRATEGY')],
  ['shadow', 'shadowCharacter', extractArray('SHADOW_CHARACTER')],
  ['shadow', 'shadowStrategy', extractArray('SHADOW_STRATEGY')],
];

for (const [, name, rows] of decks) {
  if (rows.length !== 24) throw new Error(`${name} has ${rows.length} cards, expected 24`);
}

const esc = (s) => String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");

function emit(side, deckname, rows) {
  const segment = deckname.includes('Character') ? 'character' : 'strategy';
  return rows
    .map((r, i) => {
      const [, die, title, event, ctitle, combat, hook] = r;
      const cid = `${side}_${segment}_${String(i + 1).padStart(2, '0')}`;
      const scripted = hook ? 'true' : 'false';
      const hookline = hook ? `\n    hook: ${hook},` : '';
      return `  {
    id: '${cid}', side: '${side}', deck: '${deckname}', dieToPlay: '${die}',
    title: '${esc(title)}',
    event: '${esc(event)}',
    combatTitle: '${esc(ctitle)}',
    combat: '${esc(combat)}',
    scripted: ${scripted},${hookline}
  },`;
    })
    .join('\n');
}

const header = `// AUTO-GENERATED by _carddata/gen_cards.mjs (data in gen_cards.py) — do not hand-edit.
// All 96 base-game event cards with REAL text sourced from the warofthering.eu Master Events PDFs
// (FP + Shadow), extracted via pdftotext. Four decks of 24 = 96. A subset carry a scripted \`hook\`
// the engine automates; the rest carry real text resolved by hand (scripted:false). Nothing here
// is fabricated. Deck split (Character vs Strategy) is the one CONFIRM detail (card-back).

import type { Card } from '../types';

export const CARDS: Card[] = [
`;

const body = decks.map(([side, name, rows]) => emit(side, name, rows)).join('\n');
const ts =
  header +
  body +
  '\n];\n\nexport const CARD_BY_ID: Record<string, Card> = Object.fromEntries(CARDS.map((c) => [c.id, c]));\n';

const outPath = process.argv[2];
fs.writeFileSync(outPath, ts, 'utf8');
const scripted = decks.reduce((n, [, , rows]) => n + rows.filter((r) => r[6]).length, 0);
const total = decks.reduce((n, [, , rows]) => n + rows.length, 0);
console.log(`wrote ${total} cards (${scripted} scripted) to ${outPath}`);
